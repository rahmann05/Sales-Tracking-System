import 'dotenv/config';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import jwt from 'jsonwebtoken';
import app from '../src/app.js';
import {prisma} from '../src/config/prisma.js';
import {config} from '../src/config/index.js';
import {updateUser} from '../src/modules/users/services/update-user.service.js';
import {deleteUser} from '../src/modules/users/services/delete-user.service.js';
import {CONFIG_DEFAULTS} from '../../shared/config.mjs';
import {wibDateKey} from '../../shared/visit-metrics.mjs';
assert.ok(['localhost','127.0.0.1','[::1]'].includes(new URL(process.env.DATABASE_URL).hostname));
const tag='follow-up-'+randomUUID(),users=[],activities=[];let checks=0;
const eq=(a,b)=>{assert.deepEqual(a,b);checks++;};
const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
async function api(path,user,method='GET',body){
 const current=await prisma.user.findUnique({where:{id:user.id}});
 const r=await fetch(`http://127.0.0.1:${server.address().port}/api/v1/staff-attendance${path}`,{method,headers:{'Content-Type':'application/json',Authorization:'Bearer '+jwt.sign({id:user.id,tokenVersion:current.tokenVersion},config.jwtSecret)},...(body?{body:JSON.stringify(body)}:{})});
 return {status:r.status,body:await r.json()};
}
try{
 const person=async(role,extra={})=>{const u=await prisma.user.create({data:{name:tag,email:randomUUID()+'@example.invalid',password:'unused',role,...extra}});users.push(u.id);return u;};
 const admin=await person('ADMIN'),spv=await person('SUPERVISOR'),other=await person('SUPERVISOR');
 const sales=await person('SALES',{supervisorId:spv.id}),replacement=await person('SALES',{supervisorId:spv.id}),outside=await person('SALES',{supervisorId:other.id}),denied=await person('SALES',{supervisorId:spv.id,permissions:{can_complete_follow_up:false}});
 const task=await prisma.staffActivity.create({data:{userId:spv.id,dateKey:wibDateKey(),activityKey:tag,kind:'VISIT',outletName:tag,checklist:{state:'FINISHED'},policySnapshot:{values:{...CONFIG_DEFAULTS,FOLLOW_UP_REQUIRE_REVIEW:true}},followUp:{ownerId:sales.id,ownerName:sales.name,note:'Hubungi outlet dan catat hasil kunjungan',dueDate:wibDateKey(),status:'OPEN',history:[]}}});activities.push(task.id);
 const path=`/follow-ups/${task.id}`;
 const assign=(owner,revision=0,actor=spv,extra={})=>api(`${path}/assignment`,actor,'PATCH',{ownerId:owner.id,revision,dueDate:wibDateKey(),reason:'Alihkan PIC karena jadwal kunjungan berubah',...extra});
 eq((await api('/follow-ups/candidates',spv)).body.data.map(p=>p.id).includes(outside.id),false);
 eq((await api('/follow-ups/candidates',spv)).body.data.map(p=>p.id).includes(denied.id),false);
 eq((await assign(replacement,0,sales)).status,403);
 eq((await assign(replacement,0,other)).status,404);
 eq((await assign(outside)).status,403);
 eq((await assign(denied)).status,400);
 eq((await assign(replacement,0,spv,{reason:'x'})).status,400);
 eq((await assign(replacement,0,spv,{dueDate:'2026-02-30'})).status,400);
 await assert.rejects(()=>deleteUser(sales.id),e=>e.statusCode===409);checks++;
 await assert.rejects(()=>updateUser(sales.id,{permissions:{can_complete_follow_up:false}}),e=>e.statusCode===409);checks++;
 await updateUser(spv.id,{permissions:{can_assign_follow_up:false}});
 eq((await assign(replacement)).status,403);
 await updateUser(spv.id,{permissions:{}});
 const concurrent=await Promise.all([assign(replacement),assign(replacement)]);eq(concurrent.map(r=>r.status).sort(),[200,409]);
 const saved=await prisma.staffActivity.findUnique({where:{id:task.id}});eq(saved.followUp.ownerId,replacement.id);eq(saved.followUp.revision,1);eq(saved.followUp.history.length,1);
 eq((await api(path,sales,'PATCH',{note:'Hasil oleh PIC lama',evidence:'Referensi komunikasi'})).status,404);
 eq((await deleteUser(sales.id)).id,sales.id);
 await assert.rejects(()=>deleteUser(replacement.id),e=>e.statusCode===409);checks++;
 await assert.rejects(()=>updateUser(replacement.id,{permissions:{can_view_follow_up:false}}),e=>e.statusCode===409);checks++;
 eq((await api(path,replacement,'PATCH',{note:'Outlet telah dihubungi',evidence:'Catatan percakapan dengan pemilik'})).status,200);
 eq((await assign(outside,1,admin)).status,409);
 const submitted=await prisma.staffActivity.findUnique({where:{id:task.id}}),submissionId=submitted.followUp.submission.id;
 await updateUser(spv.id,{permissions:{can_review_follow_up:false}});
 eq((await api(`${path}/review`,spv,'POST',{decision:'ACCEPT',note:'Sudah sesuai',submissionId})).status,403);
 eq((await api(`${path}/review`,other,'POST',{decision:'ACCEPT',note:'Sudah sesuai',submissionId})).status,404);
 eq((await api(`${path}/review`,admin,'POST',{decision:'RETURN',note:'Lengkapi referensi pihak yang ditemui',submissionId})).status,200);
 eq((await assign(outside,1,admin)).status,200);
 eq((await api(path,replacement,'PATCH',{note:'Hasil PIC sebelumnya',evidence:'Referensi'})).status,404);
 eq((await api(path,outside,'PATCH',{note:'Pemilik sudah dikonfirmasi',evidence:'Referensi komunikasi terbaru'})).status,200);
 const final=await prisma.staffActivity.findUnique({where:{id:task.id}});
 eq((await api(`${path}/review`,other,'POST',{decision:'ACCEPT',note:'Hasil sesuai tindak lanjut',submissionId:final.followUp.submission.id})).status,200);
 eq((await deleteUser(outside.id)).id,outside.id);
 eq((await prisma.auditEvent.count({where:{entityType:'FOLLOW_UP',entityId:task.id,action:'REASSIGN'}})),2);
 eq((await api('/follow-ups',denied)).status,200);
 await updateUser(denied.id,{permissions:{can_view_follow_up:false}});
 eq((await api('/follow-ups',denied)).status,403);
 console.log(`Follow-up assignment passed: ${checks} assertions; team scope, permissions, account protection, concurrency, reassignment and review lifecycle.`);
}finally{
 server.closeAllConnections();await new Promise(r=>server.close(r));
 await prisma.notification.deleteMany({where:{userId:{in:users}}});await prisma.auditEvent.deleteMany({where:{actorId:{in:users}}});
 await prisma.staffActivity.deleteMany({where:{id:{in:activities}}});await prisma.user.deleteMany({where:{id:{in:users}}});await prisma.$disconnect();
}
