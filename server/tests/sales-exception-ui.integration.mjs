import {renderToStaticMarkup} from 'react-dom/server';
import assert from 'node:assert/strict';
import {SalesExceptionDetail} from './src/pages/Sales/components/SalesExceptionDetail.jsx';
const render=row=>renderToStaticMarkup(<SalesExceptionDetail row={row}/>);
const row={kind:'MISSING_OUT',createdAt:'2026-10-10T02:00:00Z',details:{source:'CONTINUE_NEXT_VISIT',startedAt:'2026-10-10T01:00:00Z'}};
let html=render(row);
assert.match(html,/kunjungan ini belum memiliki absen keluar/);
assert.match(html,/Menunggu pemeriksaan SPV/);
