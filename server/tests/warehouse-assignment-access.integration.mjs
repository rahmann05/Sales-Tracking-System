 eq((await api(`/routes/${route.id}/actions`,picker,'POST',{action:'PICK',note:'Jumlah penyiapan uji sesuai muatan',cartons:1,quantities})).status,200);
 eq((await assign('CHECK',picker,2)).status,400);
 eq((await deleteUser(picker.id)).id,picker.id);
 eq((await api(`/routes/${route.id}/actions`,custom,'POST',{action:'CHECK',note:'Pemeriksaan terpisah uji sesuai muatan',cartons:1,quantities})).status,200);
 eq((await assign('CHECK',checker,2)).status,409);
 await updateUser(custom.id,{permissions:{}});
 eq((await prisma.deliveryRoute.findUnique({where:{id:route.id}})).status,'READY');
 const dashboard=await api('/operations',admin);eq(dashboard.status,200);
 eq(dashboard.body.data.people.find(p=>p.id===custom.id).permissions.can_manage_delivery_routes,false);
 eq(Object.hasOwn(dashboard.body.data.people.find(p=>p.id===custom.id),'password'),false);
 await prisma.deliveryRoute.update({where:{id:route.id},data:{status:'PARTIAL',returnedAt:new Date()}});
 await prisma.deliveryStop.update({where:{id:stop.id},data:{status:'PARTIAL_REJECT',rejectedCartons:1,rejectedItems:[{lineId,quantity:2}]}});
 const assignReturn=(owner,revision=0)=>api(`/stops/${stop.id}/return-assignment`,admin,'PATCH',{ownerId:owner?.id||null,revision,dueAt:new Date(Date.now()+86400000).toISOString(),reason:'Alihkan pemeriksaan retur kepada PIC berwenang'});
 for(const owner of [driver,hidden,hiddenAdmin])eq((await assignReturn(owner)).status,400);
 eq((await assignReturn(checker)).status,200);
 await rejects(()=>updateUser(checker.id,{permissions:{can_monitor_delivery:false}}),409);
 await rejects(()=>updateUser(checker.id,{role:'SALES'}),409);
 await rejects(()=>deleteUser(checker.id),409);
 eq((await assignReturn(custom,1)).status,200);
 eq((await deleteUser(checker.id)).id,checker.id);
 const noMonitor={...permissions,can_manage_delivery_routes:false,can_monitor_delivery:false};
 await rejects(()=>updateRole(code,{defaultPermissions:noMonitor},admin),409);
 await updateUser(custom.id,{permissions:{can_monitor_delivery:true}});
 await updateRole(code,{defaultPermissions:noMonitor},admin);
 await rejects(()=>updateUser(custom.id,{permissions:{}}),409);
 const receipt={note:'Retur uji diperiksa sesuai jumlah fisik',receivedCartons:1,reusableCartons:1,items:[{lineId,received:2,reusable:2}],reusableInvoices:[]};
 eq((await api(`/stops/${stop.id}/return`,denied,'POST',receipt)).status,403);
 eq((await assignReturn(null,2)).status,200);
 await updateUser(custom.id,{permissions:{}});
 eq((await api(`/stops/${stop.id}/return`,custom,'POST',receipt)).status,403);
 eq((await prisma.deliveryStop.findUnique({where:{id:stop.id}})).returnInspection,null);
 eq((await assignReturn(checker,3)).status,400);
 eq((await assignReturn(denied,3)).status,200);
 const receipts=await Promise.all([api(`/stops/${stop.id}/return`,denied,'POST',receipt),api(`/stops/${stop.id}/return`,denied,'POST',receipt)]);
 eq(receipts.map(r=>r.status).sort(),[200,409]);
 eq((await prisma.deliveryStop.findUnique({where:{id:stop.id}})).returnReceivedBy,denied.id);
 eq((await deleteUser(denied.id)).id,denied.id);
 console.log(`Warehouse assignment access passed: ${checks} assertions; effective permissions, separate checker, account/role protection, preparation revisions, return reassignment and concurrent receipt.`);
