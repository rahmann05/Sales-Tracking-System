export async function seedFleet(db, users, date) {
  const createdAt = at(date, '06:00');
  const photoUpdatedAt = at(date, '06:30');
  const maintenancePolicy = {
    oilChangeIntervalKm: 5000,
    oilFilterIntervalKm: 10000,
    brakePadIntervalKm: 20000,
    requireWorkshopGps: true,
    requireReceiptPhoto: true,
  };

  const vehicles = [];
  for (const [idx, row] of BELFOODS_FLEET.entries()) {
    const vehicleId = id(`vehicle-${row.plate}`);
    const photoUrl = makeEvidencePng('vehicle', idx + 1);
    const vehicle = await db.vehicle.upsert({
      where: { code: row.plate },
      update: {},
      create: {
        id: vehicleId,
        code: row.plate,
        name: `${row.modelName} (${row.plate})`,
        maxCartons: row.maxCartons,
        maxWeightKg: row.maxWeightKg,
        fuelKmPerLiter: row.fuelKmPerLiter,
        fuelType: row.fuelType,
        fuelPricePerLiter: row.fuelPricePerLiter,
        isActive: true,
        condition: row.condition,
        totalKm: row.totalKm,
        estimatedKm: row.totalKm,
        lastOilChangeKm: row.lastServiceOffset,
        lastOilFilterChangeKm: row.lastServiceOffset - 2000,
        lastBrakePadChangeKm: row.lastServiceOffset - 6000,
        photoUrl,
        photoUpdatedAt,
        capacityProfile: {
          status: 'VERIFIED',
          category: row.category,
          source: 'BELFOODS_ARMADA_MASTER',
          sourceDate: date,
          importedAt: createdAt.toISOString(),
          historicalAssignment: {
            driver: row.driverHistory,
            helper: row.helperHistory,
            region: row.region,
          },
          notes: `Armada distribusi Belfoods area ${row.region}.`,
        },
        maintenancePolicy,
        createdAt,
        updatedAt: createdAt,
      },
    });
    vehicles.push(vehicle);

    if (row.workshop) {
      const svcDateKey = offsetDate(date, row.workshop.daysAgo);
      const svcId = id(`vehicle-service-${row.plate}`);
      await db.vehicleServiceRecord.upsert({
        where: { id: svcId },
        update: {},
        create: {
          id: svcId,
          vehicleId: vehicle.id,
          requestId: id(`vehicle-service-req-${row.plate}`),
          serviceDate: at(svcDateKey, '10:30'),
          workshopName: row.workshop.name,
          serviceType: row.workshop.serviceType,
          serviceTypes: row.workshop.serviceTypes,
          receiptPhotoUrl: makeEvidencePng('service', idx + 1),
          workshopLatitude: row.workshop.lat,
          workshopLongitude: row.workshop.lng,
          cost: row.workshop.cost,
          odometerAtService: row.lastServiceOffset,
          notes: `Perawatan berkala ${row.plate} di ${row.workshop.name}.`,
          evidence: {
            source: 'DEVICE_GPS',
            actorId: users.gudang.id,
            actorName: users.gudang.name,
            actorRole: 'KEPALA_GUDANG',
            proxyEntry: false,
            latitude: row.workshop.lat,
            longitude: row.workshop.lng,
            mapsUrl: `https://www.google.com/maps/search/?api=1&query=${row.workshop.lat},${row.workshop.lng}`,
          },
          policySnapshot: operationalPolicy(svcDateKey),
          createdAt: at(svcDateKey, '10:35'),
          updatedAt: at(svcDateKey, '10:35'),
        },
      });
    }
  }

  return vehicles;
}
