// Explicit local integration check. Creates uniquely identified fixtures and removes them in finally.
import 'dotenv/config';
import assert from 'node:assert/strict';
import jwt from 'jsonwebtoken';
import { config } from '../src/config/index.js';
import { httpServer } from '../src/app.js';
import { randomUUID } from 'node:crypto';
import { prisma } from '../src/config/prisma.js';
import { savePacking, transitionPacking, draftFromApprovedOrder } from '../src/modules/delivery/services/packing-workflow.service.js';
import { createDeliveryRoute } from '../src/modules/delivery/services/create-delivery-route.service.js';
import { updateStopStatus } from '../src/modules/delivery/services/update-stop-status.service.js';
import { rejectOrder } from '../src/modules/orders/services/reject-order.service.js';
import { getPackingLists } from '../src/modules/delivery/services/get-packing-lists.service.js';
import { invalidateConfigCache } from '../src/modules/config/services/dynamic-config.service.js';
const host = new URL(process.env.DATABASE_URL).hostname;
assert.ok(['localhost','127.0.0.1','[::1]'].includes(host), 'Local DB only');
const originalConfig = prisma.systemConfig.findMany;
let policy = {};
prisma.systemConfig.findMany = async () => Object.entries(policy).map(([key,value])=>({key,value}));
const setPolicy = p => { policy=p; invalidateConfigCache(); };
const packingIds=[], orderIds=[]; let fixtureVehicle,fixtureDriver;
let checks=0;
const check = (actual,expected) => { assert.deepEqual(actual,expected); checks++; };
const rejects = async work => { await assert.rejects(work); checks++; };
try {
 const admin = await prisma.user.findFirst({where:{role:'ADMIN',deletedAt:null}});
 const driver = await prisma.user.create({data:{name:'Packing verification',email:`${randomUUID()}@example.invalid`,password:'fixture',role:'SUPIR'}});fixtureDriver=driver.id;
 const vehicle = await prisma.vehicle.create({data:{code:randomUUID(),name:'Packing verification',maxCartons:100,maxWeightKg:1000,fuelKmPerLiter:5,fuelType:'DIESEL',fuelPricePerLiter:10000}});fixtureVehicle=vehicle.id;
 const stop = await prisma.pjpStop.findFirst({include:{pjp:true}});
 const product = await prisma.product.findFirst({where:{deletedAt:null}});
 assert.ok(admin && driver && vehicle && stop && product,'Local master fixtures required');
 const base = {outletId:stop.outletId,totalCartons:10,totalWeight:10,items:[{name:'Test product',sku:'TEST',unit:'unit',quantity:100}],invoices:[{invoiceNumber:`VERIFY-${randomUUID()}`,totalCartons:10}],notes:'Temporary integration fixture'};
 let pl=await savePacking(base,admin.id); packingIds.push(pl.id); check(pl.status,'DRAFT');
 const warehouse=await getPackingLists({search:pl.code},'KEPALA_GUDANG'); check(warehouse.total,0);
 const routeData = qty => ({date:'2026-10-06',plannedStartAt:qty===4?'2026-10-06T01:00:00Z':'2026-10-06T03:00:00Z',plannedEndAt:qty===4?'2026-10-06T03:00:00Z':'2026-10-06T05:00:00Z',vehicleId:vehicle.id,driverId:driver.id,stops:[{packingListId:pl.id,outletId:stop.outletId,sequence:1,allocatedCartons:qty,allocatedInvoices:[{invoiceId:pl.invoices[0].id,cartons:qty}],allocatedItems:[{lineId:pl.items[0].lineId,quantity:qty*10}]}]});
 await rejects(()=>createDeliveryRoute(routeData(4),admin.id));
 await transitionPacking(pl.id,'RELEASE',admin.id);
 check((await getPackingLists({search:pl.code},'KEPALA_GUDANG')).total,1);
 const first=await createDeliveryRoute(routeData(4),admin.id); check(first.totalCartons,4);
 await rejects(()=>transitionPacking(pl.id,'RECALL',admin.id));
 const attempts=await Promise.allSettled([createDeliveryRoute(routeData(6),admin.id),createDeliveryRoute(routeData(6),admin.id)]);
 check(attempts.filter(r=>r.status==='fulfilled').length,1);
 const second=attempts.find(r=>r.status==='fulfilled').value;
 check((await getPackingLists({search:pl.code},'ADMIN')).items[0].remainingCartons,0);
 await prisma.deliveryRoute.updateMany({where:{id:{in:[first.id,second.id]}},data:{status:'IN_TRANSIT'}});
 await updateStopStatus(first.stops[0].id,{status:'DELIVERED',photoUrl:'data:image/png;base64,dGVzdA=='},driver.id);
 check((await prisma.invoice.findFirst({where:{packingListId:pl.id}})).isDelivered,false);
 await updateStopStatus(second.stops[0].id,{status:'DELIVERED',photoUrl:'data:image/png;base64,dGVzdA=='},driver.id);
 check((await prisma.invoice.findFirst({where:{packingListId:pl.id}})).isDelivered,true);
 await rejects(()=>updateStopStatus(second.stops[0].id,{status:'REJECTED',rejectReason:'retry'},driver.id));
 const order=await prisma.order.create({data:{pjpStopId:stop.id,createdBy:stop.pjp.userId,status:'PENDING_APPROVAL',totalValue:100,items:{create:{productId:product.id,quantity:100,unitPrice:1,subtotal:100}}},include:{items:true}});orderIds.push(order.id);
 const orderBase={...base,sourceOrderId:order.id,items:[{lineId:order.items[0].id,sourceOrderItemId:order.items[0].id,sku:product.sku,name:product.name,quantity:100,unit:'unit'}],invoices:[{invoiceNumber:`VERIFY-${randomUUID()}`,totalCartons:10}]};
 await rejects(()=>savePacking(orderBase,admin.id));
 setPolicy({PACKING_ALLOW_PENDING_ORDER:true});
 await rejects(()=>savePacking(orderBase,admin.id));
 let manual=await savePacking({...orderBase,overrideReason:'Approved test override'},admin.id);packingIds.push(manual.id);
 check((await prisma.order.findUnique({where:{id:order.id}})).status,'PENDING_APPROVAL');
 await rejects(()=>savePacking({...orderBase,overrideReason:'Reason',revision:99},admin.id,manual.id));
 await transitionPacking(manual.id,'RELEASE',admin.id);
 await rejects(()=>rejectOrder(order.id,admin.id,'Cannot reject an order already released'));
 setPolicy({PACKING_AUTO_RELEASE:true});
 const auto=await savePacking({...base,invoices:[{invoiceNumber:`VERIFY-${randomUUID()}`,totalCartons:10}]},admin.id);packingIds.push(auto.id);check(auto.status,'RELEASED');
 await transitionPacking(auto.id,'RECALL',admin.id);check((await prisma.packingList.findUnique({where:{id:auto.id}})).history.length,2);
 setPolicy({PACKING_SOURCE_MODE:'ORDER'});await rejects(()=>savePacking(base,admin.id));
 const order2=await prisma.order.create({data:{pjpStopId:stop.id,createdBy:stop.pjp.userId,status:'APPROVED',totalValue:100,items:{create:{productId:product.id,quantity:2,unitPrice:50,subtotal:100}}}});orderIds.push(order2.id);
 setPolicy({PACKING_SOURCE_MODE:'BOTH',PACKING_AUTO_FROM_APPROVED_ORDER:true});
 await prisma.$transaction(tx=>draftFromApprovedOrder(tx,order2.id,admin.id));
 const generated=await prisma.packingList.findFirst({where:{sourceOrderId:order2.id}});packingIds.push(generated.id);check(generated.status,'DRAFT');check(generated.totalCartons,0);check(generated.items[0].quantity,2);
 await prisma.$transaction(tx=>draftFromApprovedOrder(tx,order2.id,admin.id));check(await prisma.packingList.count({where:{sourceOrderId:order2.id}}),1);
 setPolicy({});
 await new Promise(resolve=>httpServer.listen(0,'127.0.0.1',resolve));
 const endpoint=`http://127.0.0.1:${httpServer.address().port}/api/v1/delivery/packing-lists`;
 const warehouseUser=await prisma.user.findFirst({where:{role:'KEPALA_GUDANG',deletedAt:null}});
 assert.ok(warehouseUser,'Warehouse user fixture');
 const headersFor=role=>({'Content-Type':'application/json',Authorization:`Bearer ${jwt.sign({id:role==='ADMIN'?admin.id:warehouseUser.id,role},config.jwtSecret,{expiresIn:'1m'})}`});
 const forbidden=await fetch(endpoint,{method:'POST',headers:headersFor('KEPALA_GUDANG'),body:JSON.stringify(base)});check(forbidden.status,403);
 const httpCreated=await fetch(endpoint,{method:'POST',headers:headersFor('ADMIN'),body:JSON.stringify({outletId:stop.outletId,totalCartons:0})});
 check(httpCreated.status,201);const httpDoc=(await httpCreated.json()).data;packingIds.push(httpDoc.id);check(httpDoc.items,[]);
 const invalidRelease=await fetch(`${endpoint}/${httpDoc.id}/status`,{method:'PATCH',headers:headersFor('ADMIN'),body:JSON.stringify({action:'RELEASE'})});check(invalidRelease.status,400);
 await new Promise(resolve=>httpServer.close(resolve));
 console.log(`Packing integration passed: ${checks} checks, including concurrent allocations and split delivery.`);
} finally {
 const docs=await prisma.packingList.findMany({where:{OR:[{id:{in:packingIds}},{sourceOrderId:{in:orderIds}}]},select:{id:true}});
 const ids=docs.map(d=>d.id);
 const stops=await prisma.deliveryStop.findMany({where:{packingListId:{in:ids}},select:{deliveryRouteId:true}});
 await prisma.deliveryRoute.deleteMany({where:{id:{in:stops.map(s=>s.deliveryRouteId)}}});
 await prisma.packingList.deleteMany({where:{id:{in:ids}}});
 await prisma.order.deleteMany({where:{id:{in:orderIds}}});
 if (httpServer.listening) await new Promise(resolve=>httpServer.close(resolve));
 if(fixtureVehicle)await prisma.vehicle.delete({where:{id:fixtureVehicle}});if(fixtureDriver)await prisma.user.delete({where:{id:fixtureDriver}});
 prisma.systemConfig.findMany=originalConfig; invalidateConfigCache();await prisma.$disconnect();
}
