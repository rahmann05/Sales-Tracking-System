import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { prisma } from '../src/config/prisma.js';
import { assignTeam, listTeams } from '../src/modules/teams/teams.service.js';
import { updateCluster } from '../src/modules/clusters/services/update-cluster.service.js';
import { saveTemplates } from '../src/modules/pjp/services/templates.service.js';
import { assertSalesAccess } from '../src/utils/team-scope.js';
import { correctCoordinates } from '../src/modules/outlets/services/correct-coordinates.service.js';
import { validateOutlet } from '../src/modules/outlets/services/validate-outlet.service.js';
import { invalidateConfigCache } from '../src/modules/config/services/dynamic-config.service.js';
assert.ok(['localhost','127.0.0.1','[::1]'].includes(new URL(process.env.DATABASE_URL).hostname));
const prefix=`verify-${randomUUID()}`;
const userIds=[],clusterIds=[],outletIds=[];
const originalFetch=globalThis.fetch, originalConfig=prisma.systemConfig.findMany;
let settings={MAPS_API_KEY:'fixture',TEAM_SPV_CAN_CLAIM_UNASSIGNED:true};
prisma.systemConfig.findMany=async()=>Object.entries(settings).map(([key,value])=>({key,value}));invalidateConfigCache();
let count=0;
const check=(actual,expected)=>{assert.deepEqual(actual,expected);count++;};
const rejects=async(fn,status)=>{await assert.rejects(fn,status?e=>e.statusCode===status:undefined);count++;};
const createUser=async role=>{const u=await prisma.user.create({data:{name:prefix,email:`${randomUUID()}@example.invalid`,password:'fixture',role}});userIds.push(u.id);return u;};
try {
 const admin=await createUser('ADMIN'),spv=await createUser('SUPERVISOR'),other=await createUser('SUPERVISOR'),sales=await createUser('SALES');
 const cluster=await prisma.cluster.create({data:{name:prefix,region:'Bandung',supervisorId:spv.id}});clusterIds.push(cluster.id);
 const outlet=await prisma.outlet.create({data:{name:'Toko Aska',address:'Jalan Bandung 1',latitude:-6.9,longitude:107.6,clusterId:cluster.id}});outletIds.push(outlet.id);
 const revision=async()=> (await prisma.user.findUnique({where:{id:sales.id}})).updatedAt.toISOString();
 const assignment=async(owner,actor=admin)=>assignTeam(sales.id,{supervisorId:owner,updatedAt:await revision(),reason:'Penugasan tim pengujian'},actor);
 check((await listTeams(spv)).sales.some(s=>s.id===sales.id),true);
 settings.TEAM_SPV_CAN_CLAIM_UNASSIGNED=false;invalidateConfigCache();
 await rejects(()=>assignment(spv.id,spv),403);
 settings.TEAM_SPV_CAN_CLAIM_UNASSIGNED=true;invalidateConfigCache();
 const stale=await revision();await assignment(spv.id,spv);
 check((await prisma.user.findUnique({where:{id:sales.id}})).supervisorId,spv.id);
 await assertSalesAccess(spv,sales.id);count++;
 await rejects(()=>assertSalesAccess(other,sales.id),403);
 await rejects(()=>assignTeam(sales.id,{supervisorId:other.id,updatedAt:stale,reason:'Ubah stale revision'},admin),409);
 await rejects(()=>assignment(other.id,other),403);
 await rejects(()=>updateCluster(cluster.id,{assignedSalesId:sales.id,supervisorId:other.id},admin),400);
 await updateCluster(cluster.id,{assignedSalesId:sales.id},admin);
 check((await prisma.user.findUnique({where:{id:sales.id}})).clusterId,cluster.id);
 await saveTemplates([{userId:sales.id,dayOfWeek:1,weekType:'ALL',outletIds:[outlet.id]}],spv);
 const plan=await prisma.pjp.create({data:{userId:sales.id,date:new Date('2026-01-01T00:00:00Z'),type:'SALES',stops:{create:{outletId:outlet.id,sequence:1}}}});
 const sameRevision=await revision();
 const transfers=await Promise.allSettled([assignTeam(sales.id,{supervisorId:other.id,updatedAt:sameRevision,reason:'Transfer tim tujuan'},admin),assignTeam(sales.id,{supervisorId:null,updatedAt:sameRevision,reason:'Lepaskan ke tanpa tim'},admin)]);
 check(transfers.filter(r=>r.status==='fulfilled').length,1);
 check(transfers.filter(r=>r.status==='rejected' && r.reason.statusCode===409).length,1);
 check((await prisma.cluster.findUnique({where:{id:cluster.id}})).assignedSalesId,null);
 check((await prisma.user.findUnique({where:{id:sales.id}})).clusterId,null);
 check(await prisma.pjpTemplate.count({where:{userId:sales.id}}),0);
 check(await prisma.pjpStop.count({where:{pjpId:plan.id}}),1);
 await rejects(()=>assertSalesAccess(spv,sales.id),403);
 check(await prisma.notification.count({where:{userId:sales.id,type:'TEAM_ASSIGNMENT'}}),2);
 const before=await prisma.outlet.findUnique({where:{id:outlet.id}});
 await rejects(()=>correctCoordinates(outlet.id,{latitude:91,longitude:107,updatedAt:before.updatedAt.toISOString(),reason:'GPS setelah pengecekan'},admin));
 await rejects(()=>correctCoordinates(outlet.id,{latitude:-6.8,longitude:107,updatedAt:before.updatedAt.toISOString(),reason:'GPS setelah pengecekan'},other),403);
 const corrections=await Promise.allSettled([1,2].map(i=>correctCoordinates(outlet.id,{latitude:-6.8,longitude:107+i/100,updatedAt:before.updatedAt.toISOString(),reason:'GPS berdasarkan pengecekan lapangan'},admin)));
 check(corrections.filter(r=>r.status==='fulfilled').length,1);
 check(corrections.filter(r=>r.status==='rejected' && r.reason.statusCode===409).length,1);
 const corrected=await prisma.outlet.findUnique({where:{id:outlet.id}});
 check(corrected.validationStatus,'UNVALIDATED');check(corrected.validationDetails.coordinateHistory.length,1);
 globalThis.fetch=async()=>new Response(JSON.stringify({status:'REQUEST_DENIED'}));
 await rejects(()=>validateOutlet(outlet.id),503);
 check((await prisma.outlet.findUnique({where:{id:outlet.id}})).validationStatus,'UNVALIDATED');
 check((await prisma.outlet.findUnique({where:{id:outlet.id}})).updatedAt.toISOString(),corrected.updatedAt.toISOString());
 await prisma.outlet.update({where:{id:outlet.id},data:{googleSuggestedLat:-6,googleSuggestedLng:106}});
 globalThis.fetch=async()=>new Response(JSON.stringify({status:'ZERO_RESULTS',results:[],candidates:[]}));
 await validateOutlet(outlet.id);
 const compared=await prisma.outlet.findUnique({where:{id:outlet.id}});
 check(compared.googleSuggestedLat,null);check(compared.googleSuggestedLng,null);check(compared.validationDetails.coordinateHistory.length,1);
 check(compared.validationDetails.warnings.some(w=>w.includes('terkonfirmasi')),false);
 globalThis.fetch=async()=>{await prisma.outlet.update({where:{id:outlet.id},data:{address:'Alamat diubah saat validasi'}});return new Response(JSON.stringify({status:'ZERO_RESULTS',results:[],candidates:[]}));};
 await rejects(()=>validateOutlet(outlet.id),409);
 console.log(`Team/outlet integration passed: ${count} checks, including concurrent transfer/correction, preserved PJP, provider failure and stale candidates.`);
} finally {
 globalThis.fetch=originalFetch;prisma.systemConfig.findMany=originalConfig;invalidateConfigCache();
 const plans=await prisma.pjp.findMany({where:{userId:{in:userIds}},select:{id:true}});
 await prisma.pjpStop.deleteMany({where:{pjpId:{in:plans.map(p=>p.id)}}});await prisma.pjp.deleteMany({where:{userId:{in:userIds}}});
 await prisma.pjpTemplate.deleteMany({where:{userId:{in:userIds}}});
 await prisma.user.updateMany({where:{id:{in:userIds}},data:{clusterId:null,supervisorId:null}});
 await prisma.cluster.updateMany({where:{id:{in:clusterIds}},data:{assignedSalesId:null,supervisorId:null}});
 await prisma.outlet.deleteMany({where:{id:{in:outletIds}}});await prisma.cluster.deleteMany({where:{id:{in:clusterIds}}});await prisma.user.deleteMany({where:{id:{in:userIds}}});await prisma.$disconnect();
}
