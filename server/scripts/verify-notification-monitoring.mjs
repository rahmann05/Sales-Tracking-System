import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import jwt from 'jsonwebtoken';
import { prisma } from '../src/config/prisma.js';
import { config } from '../src/config/index.js';
import { httpServer } from '../src/app.js';
import { schedulerMonitor } from '../src/utils/scheduler-health.js';
import { completeFollowUp, reviewFollowUp, listFollowUps } from '../src/modules/staff-attendance/follow-up.service.js';
import { notifyFollowUp } from '../src/modules/staff-attendance/follow-up-notification.service.js';
assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(new URL(process.env.DATABASE_URL).hostname), 'Local database only');
const users = []; let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
try {
  for (const role of ['ADMIN', 'SUPERVISOR', 'SALES', 'KEPALA_GUDANG', 'SUPIR']) users.push(await prisma.user.create({ data: { name: 'Notification verification', email: `${randomUUID()}@example.invalid`, password: 'fixture', role } }));
  await prisma.notification.createMany({ data: users.flatMap(user => Array.from({ length: 105 }, (_, i) => ({ userId: user.id, type: 'ORDER_REVIEW_ASSIGNED', title: `Tugas ${i}`, message: 'Periksa pekerjaan terbaru di antrean', isRead: i === 0 }))) });
  await new Promise(resolve => httpServer.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${httpServer.address().port}/api/v1`;
  const call = (path, user, method = 'GET') => fetch(`${base}${path}`, { method, headers: user ? { Authorization: `Bearer ${jwt.sign({ id: user.id, role: user.role }, config.jwtSecret, { expiresIn: '5m' })}` } : {} });
  check((await call('/notifications')).status, 401);
  check((await call('/health/monitoring')).status, 401);
  for (const user of users) {
    const response = await call('/notifications', user); check(response.status, 200);
    const data = (await response.json()).data;
    check(data.total, 105); check(data.unreadCount, 104); check(data.notifications.every(n => n.userId === user.id), true); check(data.hasMore, true);
    const ids = new Set(data.notifications.map(n => n.id));
    const second = (await (await call('/notifications?page=2', user)).json()).data;
    check(second.notifications.every(n => !ids.has(n.id)), true);
    const foreign = await prisma.notification.findFirst({ where: { userId: users.find(u => u.id !== user.id).id } });
    check((await call(`/notifications/${foreign.id}/read`, user, 'PATCH')).status, 404);
    check((await call(`/notifications/${data.notifications[0].id}/read`, user, 'PATCH')).status, 200);
    check((await prisma.notification.findUnique({ where: { id: data.notifications[0].id } })).isRead, true);
    check((await call('/notifications/read-all', user, 'PATCH')).status, 200);
    check((await (await call('/notifications', user)).json()).data.unreadCount, 0);
    check((await call('/health/monitoring', user)).status, user.role === 'ADMIN' ? 200 : 403);
  }
  schedulerMonitor.register('VERIFY', 'Test scheduler', Date.now() + 1000, 1000);
  await assert.rejects(() => schedulerMonitor.run('VERIFY', async () => { throw new Error('secret internal diagnostic'); }, now => now + 1000));
  const failed = await call('/health/monitoring', users[0]); check(failed.headers.get('cache-control'), 'no-store');
  const failureData = (await failed.json()).data; check(failureData.jobs[0].status, 'FAILED'); check(JSON.stringify(failureData).includes('secret internal diagnostic'), false);
  await schedulerMonitor.run('VERIFY', async () => {}, now => now + 1000);
  check((await (await call('/health/monitoring', users[0])).json()).data.jobs[0].status, 'OK');
  const [admin, spv, sales] = users;
  await prisma.user.update({ where: { id: sales.id }, data: { supervisorId: spv.id } });
  const activity = await prisma.staffActivity.create({ data: { userId: spv.id, dateKey: '2026-10-08', activityKey: randomUUID(), kind: 'VISIT', outletName: 'Toko pengujian', followUp: { ownerId: sales.id, status: 'OPEN', dueDate: '2026-10-09', history: [] } } });
  await prisma.$transaction(tx => notifyFollowUp(tx, activity, 'ASSIGNED', spv.id));
  check(await prisma.notification.count({ where: { userId: sales.id, type: 'FOLLOW_UP_ASSIGNED' } }), 1);
  const submitted = await completeFollowUp(activity.id, sales, 'Sudah dikunjungi', 'Referensi komunikasi');
  check(await prisma.notification.count({ where: { userId: spv.id, type: 'FOLLOW_UP_SUBMITTED' } }), 1);
  check(await prisma.notification.count({ where: { userId: admin.id, type: 'FOLLOW_UP_SUBMITTED' } }), 0);
  await reviewFollowUp(activity.id, spv, { decision: 'RETURN', note: 'Lengkapi hasil', submissionId: submitted.followUp.submission.id });
  check(await prisma.notification.count({ where: { userId: sales.id, type: 'FOLLOW_UP_RETURNED' } }), 1);
  const resubmitted = await completeFollowUp(activity.id, sales, 'Hasil dilengkapi', 'Referensi baru');
  await reviewFollowUp(activity.id, spv, { decision: 'ACCEPT', note: 'Bukti cukup', submissionId: resubmitted.followUp.submission.id });
  check(await prisma.notification.count({ where: { userId: sales.id, type: 'FOLLOW_UP_ACCEPTED' } }), 1);
  check((await prisma.staffActivity.findUnique({ where: { id: activity.id } })).followUp.status, 'DONE');
  const nextSpv = await prisma.user.create({ data: { name: 'Reviewer transfer verification', email: `${randomUUID()}@example.invalid`, password: 'fixture', role: 'SUPERVISOR' } }); users.push(nextSpv);
  await prisma.user.update({ where: { id: sales.id }, data: { supervisorId: nextSpv.id } });
  const moved = await prisma.staffActivity.create({ data: { userId: spv.id, dateKey: '2026-10-08', activityKey: randomUUID(), kind: 'VISIT', followUp: { ownerId: sales.id, status: 'OPEN', dueDate: '2026-10-09', history: [] } } });
  check((await listFollowUps(nextSpv)).some(task => task.id === moved.id), true);
  const movedResult = await completeFollowUp(moved.id, sales, 'Hasil setelah pindah tim', 'Referensi');
  check(await prisma.notification.count({ where: { userId: nextSpv.id, type: 'FOLLOW_UP_SUBMITTED' } }), 1);
  const nextQueue = (await (await call('/attention?filter=REVIEW', nextSpv)).json()).data;
  check(nextQueue.rows.some(row => row.activityId === moved.id), true);
  await reviewFollowUp(moved.id, nextSpv, { decision: 'ACCEPT', note: 'Diperiksa SPV saat ini', submissionId: movedResult.followUp.submission.id });
  check((await prisma.staffActivity.findUnique({ where: { id: moved.id } })).followUp.status, 'DONE');
  console.log(`Notification and monitoring integration passed: ${checks} checks across all five roles, recipient isolation, pagination, persistent reads, scheduler failures and recovery.`);
} finally {
  if (httpServer.listening) await new Promise(resolve => httpServer.close(resolve));
  await prisma.notification.deleteMany({ where: { userId: { in: users.map(u => u.id) } } });
  await prisma.staffActivity.deleteMany({ where: { userId: { in: users.map(u => u.id) } } });
  await prisma.user.deleteMany({ where: { id: { in: users.map(u => u.id) } } });
  await prisma.$disconnect();
}
