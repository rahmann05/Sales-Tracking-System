import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {locationPresentation} from '../../client/src/pages/TeamTracking/locationPresentation.js';
const require=createRequire(new URL('../../client/package.json',import.meta.url));
const {buildSync}=require('esbuild');
const result=buildSync({entryPoints:[fileURLToPath(new URL('../../client/src/constants/supervisorNavigation.js',import.meta.url))],bundle:true,platform:'node',format:'esm',write:false,logLevel:'silent'});
const {getSupervisorNavigationGroups,supervisorParentTab}=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const supervisor={role:'SUPERVISOR',permissions:{can_approve_order:true,can_unlock_absensi:true}};
const groups=getSupervisorNavigationGroups(supervisor);
assert.equal(groups.length,7);
const items=groups.flatMap(group=>group.items.map(item=>item.id));
assert.equal(new Set(items).size,items.length,'Each feature has one navigation owner');
assert.equal(items.includes('admin-products'),false);
assert.equal(items.includes('admin-attendance'),false);
assert.equal(items.includes('admin-approval'),false,'Legacy approval entry is normalized');
assert.equal(items.includes('daily-call-monitor'),false,'Monitoring has one primary entry');
for(const role of ['ADMIN','SALES','SUPIR','KEPALA_GUDANG'])assert.deepEqual(getSupervisorNavigationGroups({role}),[]);
assert.equal(supervisorParentTab('admin-approval'),'spv-approval');
assert.equal(supervisorParentTab('daily-call-monitor'),'spv-monitor');
assert.equal(supervisorParentTab('create-cluster'),'route-planning');
const restricted=getSupervisorNavigationGroups({role:'SUPERVISOR',permissions:{can_view_daily_call:false,can_view_live_tracking:false,can_view_reports:false,can_view_outlet_report:false,can_manage_outlets:false,can_validate_outlet:false,can_approve_outlet:false,can_view_dashboard:false,can_register_outlet:false}});
assert.equal(restricted.some(group=>group.id==='monitor'),false);
assert.equal(restricted.some(group=>group.id==='reports'),false);
assert.equal(restricted.some(group=>group.id==='outlets'),false);
assert.equal(restricted.flatMap(group=>group.items).some(item=>item.id==='outlet-approval'),false);
const now=Date.parse('2026-10-08T08:00:00Z');
const point={latitude:-6.8,longitude:107.6,lastUpdated:'2026-10-08T07:59:00Z'};
assert.equal(locationPresentation({...point,locationSource:'LIVE_GPS_PING'},now).label,'GPS terkini');
assert.equal(locationPresentation({...point,locationSource:'LIVE_GPS_PING',lastUpdated:'2026-10-08T06:00:00Z'},now).label,'GPS lama');
assert.equal(locationPresentation({...point,locationSource:'LAST_ATTENDANCE',isOnline:true},now).label,'Titik absensi terakhir');
for(const locationSource of ['DEFAULT','CLUSTER_CENTER',undefined])assert.equal(locationPresentation({...point,locationSource},now).hasPosition,false,'Reference points must never represent a person');
for(const patch of [{latitude:null},{longitude:Infinity},{latitude:91},{lastUpdated:null}])assert.equal(locationPresentation({...point,locationSource:'LIVE_GPS_PING',...patch},now).hasPosition,false);
assert.equal(locationPresentation({...point,locationSource:'LIVE_GPS_PING',lastUpdated:'2026-10-08T09:00:00Z'},now).tone,'stale');
process.stdout.write('Supervisor UI verification passed: module ownership, role and permission filtering, legacy links, live/stale/attendance/missing locations and invalid coordinates.\n');
